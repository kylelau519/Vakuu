#!/bin/bash

export vakuu="/Users/kylelau519/Programming/Vakuu"
ROUND=1
# This loop runs no facility of its own -- every select_map_node decision on ANY facility's main
# line (facility_claws.py's data/raw, facility_choices_paradox.py's data/raw_choices) already
# carries its own trial's +1/-1 terminal outcome via facility_common.py's pending_map_steps
# wiring, so Golden Compass training data is a free byproduct of whichever of training_claws.sh /
# training_alternating.sh happens to be running -- see agents/golden_compass/model/README.md's
# Design section. So instead of a fixed self-play round, this just paces itself on a timer,
# re-materializing off whatever those loops currently have on disk.
POLL_INTERVAL="${GOLDEN_COMPASS_POLL_INTERVAL:-300}"

CKPT="$vakuu/agents/golden_compass/model/golden_compass.pt"
DATASET="$vakuu/agents/golden_compass/model/dataset.pt"

while true; do
    echo "==========================================="
    echo " Starting Golden Compass Training Loop: Round $ROUND"
    echo "==========================================="

    INIT_CKPT="$CKPT"
    [ -f "$INIT_CKPT" ] || INIT_CKPT=""

    # data/raw and data/raw_choices are each periodically wiped and regenerated by
    # training_claws.sh / training_alternating.sh -- materialize_main_trial's per-file try/except
    # already skips a trial that vanishes mid-read (see materialize.py's _materialize_main_task),
    # so racing those loops' cleanup is harmless, just occasionally fewer examples this round.
    echo "[1/3] Materializing dataset from claws + choices raw data..."
    python "$vakuu/agents/golden_compass/model/materialize.py" \
        "$vakuu/agents/whispering_earring/data/raw/" \
        "$vakuu/agents/whispering_earring/data/raw_choices/" \
        --out "$DATASET" \
        --jobs 8

    example_count=$(python -c "
import torch
print(len(torch.load('$DATASET', weights_only=False)))
" 2>/dev/null)
    example_count="${example_count:-0}"

    if [ "$example_count" -eq 0 ]; then
        echo "No usable examples yet (claws/choices loops haven't finished a trial since the " \
             "last round) -- skipping training, retrying in ${POLL_INTERVAL}s."
    else
        echo "[2/3] Training model on $example_count examples..."
        python "$vakuu/agents/golden_compass/model/train.py" \
            "$DATASET" --epochs 20 \
            --out "$CKPT" \
            --init "$INIT_CKPT"

        echo "[3/3] Backing up checkpoint..."
        # Timestamped, never overwritten -- see training_claws.sh's own comment; same reasoning here.
        backup_dir="$vakuu/agents/golden_compass/model/backups"
        mkdir -p "$backup_dir"
        cp "$CKPT" "$backup_dir/golden_compass_$(date +%Y%m%d_%H%M%S).pt"
    fi

    echo "==========================================="
    echo " Round $ROUND complete! Waiting ${POLL_INTERVAL}s..."
    echo "==========================================="
    sleep "$POLL_INTERVAL"
    ((ROUND++))
done
