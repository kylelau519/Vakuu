"""Trains ClawsNet on materialize.py's output.

Two losses, both read off the same examples (one per combat_play decision):

  value   V(state) is regressed on the HP the player actually lost from that state to the end of
          the combat (materialize.py's `value`). MSE in units of V_SCALE HP, so the loss is
          O(1) however large a combat's loss is.
  policy  only for examples inside a compared turn (`action_index` set): advantage-weighted
          log-likelihood, `-advantage * log_prob(action).clamp(min=_LOGP_FLOOR)`. The advantage
          is the group's mean cost minus this action sequence's own cost, in HP, so a positive one
          means "lost less HP than its siblings" and pushes the action up; a negative one pushes
          it down. Advantages are divided by their global std, not re-centered: each group is
          already centered on its own mean, and subtracting a global mean would shift every group.

Note policy_loss can be negative here (when advantage < 0, minimizing it means driving that
action's probability *down*). The log_prob floor exists because that push-down direction is
otherwise unbounded: log_prob(action) -> -inf as prob(action) -> 0, so a fixed dataset replayed
over many epochs (this isn't on-policy REINFORCE -- the same (state, action, advantage) triples
recur every epoch) has no equilibrium and drives every negative-advantage action's probability to
exactly 0, collapsing the whole policy to one-hot. Clamping log_prob at _LOGP_FLOOR still lets a
bad action get actively penalized (same sign, same gradient direction) but gives that penalty a
floor -- once the action's probability is low enough, the clamp zeroes the gradient instead of
chasing it further. The positive-advantage side never needed this: pushing prob(action) -> 1
saturates naturally at log_prob = 0.

Examples are batched with padding: each has a different token count and option count, so a batch
pads every example's tokens up to the batch's own max length (ClawsNet.encode_batched's
key_padding_mask keeps padded rows out of attention) and stacks every option-scoring query across
the batch into one policy_mlp call (see _batch_step).

V is on-policy: it estimates the loss under the policy that played the data, so a dataset is
only valid for the checkpoint that generated it (or the untrained init, in round 1). Don't mix
rounds generated by different checkpoints into one run.

Usage:
    python -m vakuu.claws.train dataset.pt --epochs 5 --out claws.pt --init ""  # round 1, random init
    python -m vakuu.claws.train dataset.pt --epochs 5 --out claws.pt --init claws.pt  # resume
    python -m vakuu.claws.train dataset.pt --epochs 20 --out claws.pt --init claws.pt --value-only
"""
from __future__ import annotations

import argparse
import os
import random

os.environ.setdefault("KMP_DUPLICATE_LIB_OK", "TRUE")  # see model.py's top -- two OpenMP
# runtimes (conda's llvm-openmp + torch's bundled copy) otherwise abort on import

import torch
import torch.nn.functional as F

# Still single-threaded even with real batching now (see this module's docstring) -- dim=64
# keeps every matmul small enough that PyTorch's default intra-op thread count (one per core)
# spins up a parallel region whose sync overhead outweighs the extra work available to split.
# Measured on this machine's actual dataset (6616 examples, 1 epoch): batch 32 takes 3.5s single-
# threaded vs 4.0s at 8 threads, and single-threaded batch 32 is itself ~8x faster than the old
# batch-size-1 loop's 28.9s -- the real win is from batching, not the thread count.
#
# CPU vs. GPU crossover (measured on the 61783-example dataset, this machine's RTX 3060 Mobile):
# batch 32 CPU beats GPU (29.8s vs 38.5s -- kernel-launch/transfer overhead dominates at this
# size), but CPU cost grows ~quadratically with batch size (padding every example in a batch up
# to that batch's own max length inflates the attention cost) while GPU absorbs it -- batch 256
# is roughly a tie, batch 1024 favors GPU 2x (27.3s vs 61.3s), batch 4096 favors GPU 6x. Note the
# per-example Python loop in _batch_step that builds each option's query is a fixed ~27s/epoch
# cost regardless of device or batch size, so GPU plateaus there rather than keeps improving.
torch.set_num_threads(1)

from vakuu.claws.model import ClawsNet, FEATURE_DIM, GlobalVocab, PILE_KEYS, V_SCALE
from vakuu.common.tokenizer import EntityVocab

_LOGP_FLOOR = -6.0  # ~0.25% probability -- see module docstring for why this exists


def _normalize_advantages(examples: list[dict]) -> None:
    """In-place: divides every scored example's advantage by the std of them all (see the module
    docstring for why it is not re-centered)."""
    scored = [ex["advantage"] for ex in examples if ex["action_index"] is not None]
    if not scored:
        return
    std = (sum(a * a for a in scored) / len(scored)) ** 0.5
    if std < 1e-8:
        return  # no spread -- leave as-is rather than divide by ~0
    for ex in examples:
        if ex["action_index"] is not None:
            ex["advantage"] /= std


def _collate(
    examples: list[dict],
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, dict[str, torch.Tensor], torch.Tensor]:
    """Pads a list of examples' token tensors up to the batch's own max token count. Returns
    (type_ids, global_ids, features, pad_mask), each with a leading batch dimension -- pad_mask
    is True at padded positions (see ClawsNet.encode_batched). The fifth item stacks the fixed-size
    pile tensors (PILE_KEYS) -- no padding needed, every pile is already padded to 50."""
    lens = [ex["type_ids"].shape[0] for ex in examples]
    max_len = max(lens)
    b = len(examples)
    type_ids = torch.zeros(b, max_len, dtype=torch.long)
    global_ids = torch.zeros(b, max_len, dtype=torch.long)
    group_ids = torch.zeros(b, max_len, dtype=torch.long)
    features = torch.zeros(b, max_len, FEATURE_DIM)
    pad_mask = torch.ones(b, max_len, dtype=torch.bool)
    for i, (ex, n) in enumerate(zip(examples, lens)):
        type_ids[i, :n] = ex["type_ids"]
        global_ids[i, :n] = ex["global_ids"]
        group_ids[i, :n] = ex["group_ids"]
        features[i, :n] = ex["features"]
        pad_mask[i, :n] = False
    piles = {k: torch.stack([ex[k] for ex in examples]) for k in PILE_KEYS}
    return type_ids, global_ids, features, pad_mask, piles, group_ids


def _batch_step(
    examples: list[dict], net: ClawsNet, value_only: bool, device: torch.device,
) -> tuple[torch.Tensor, float, float, int]:
    """One batch's loss, built with exactly two real matmul-bearing calls -- one
    encode_batched() for every example's tokens and one policy_mlp() call for every option
    across the whole batch -- instead of looping either per example. Per-example work here is
    just gathering which token rows feed each option's query and slicing the shared policy
    logits back apart, both cheap indexing with no thread-pool sync cost.

    Returns (loss, total_policy_loss, total_squared_error_hp, n_scored) -- the last three are
    floats/int for the caller's running epoch totals, not part of the backward graph."""
    type_ids, global_ids, features, pad_mask, piles, group_ids = _collate(examples)
    type_ids, global_ids, features, pad_mask = (
        type_ids.to(device), global_ids.to(device), features.to(device), pad_mask.to(device)
    )
    piles, group_ids = {k: v.to(device) for k, v in piles.items()}, group_ids.to(device)
    h = net.encode_batched(type_ids, global_ids, features, pad_mask, piles, group_ids)  # [B, N, dim]

    queries = []
    spans: list[tuple[int, int]] = []  # (start, count) into `queries` per example
    for b, ex in enumerate(examples):
        start = len(queries)
        hb = h[b]
        for action, args in ex["options"]:
            if action == "end_turn":
                q = net.end_turn_query + hb[ex["player_pos"]]
            elif action == "play_card":
                q = hb[ex["hand_pos"][args["card_index"]]]
                if "target_index" in args:
                    q = q + hb[ex["enemy_pos"][args["target_index"]]]
            elif action == "use_potion":
                q = hb[ex["potion_pos"][args["potion_index"]]]
                if "target_index" in args:
                    q = q + hb[ex["enemy_pos"][args["target_index"]]]
            else:
                raise ValueError(f"unhandled combat action {action!r}")
            queries.append(q)
        spans.append((start, len(queries) - start))

    all_logits = net.policy_mlp(net.with_action_features(
        torch.stack(queries), [a for ex in examples for _, a in ex["options"]])).squeeze(-1)  # [total options in batch]
    player_h = torch.stack([h[b, ex["player_pos"]] for b, ex in enumerate(examples)])
    values = net.value_in_hp(net.value_mlp(player_h).squeeze(-1))  # [B], in HP
    targets = torch.tensor([ex["value"] for ex in examples], device=device)
    value_loss = (((values - targets) / V_SCALE) ** 2).sum()

    policy_loss = torch.zeros((), device=device)
    n_scored = 0
    if not value_only:
        for b, ex in enumerate(examples):
            if ex["action_index"] is None:
                continue
            start, count = spans[b]
            log_probs = F.log_softmax(all_logits[start:start + count], dim=-1)
            log_prob = log_probs[ex["action_index"]].clamp(min=_LOGP_FLOOR)
            policy_loss = policy_loss - ex["advantage"] * log_prob
            n_scored += 1

    squared_error_hp = ((values - targets) ** 2).sum().item()
    return (policy_loss + value_loss) / len(examples), policy_loss.item(), squared_error_hp, n_scored


def _snapshot(net: ClawsNet) -> dict[str, torch.Tensor]:
    return {k: v.detach().clone() for k, v in net.state_dict().items()}


def _count_changed(before: dict[str, torch.Tensor], after: dict[str, torch.Tensor]) -> tuple[int, int]:
    """Exact (not near-) equality: how many scalars in the whole network moved at all this epoch.
    Sparse inputs (e.g. an embedding table) leave rows for unseen entities bit-for-bit unchanged,
    so this doubles as a per-epoch coverage signal, not just a "did training run" sanity check."""
    changed = total = 0
    for k, b in before.items():
        a = after[k]
        total += a.numel()
        changed += int((a != b).sum().item())
    return changed, total


def _l2_delta(before: dict[str, torch.Tensor], after: dict[str, torch.Tensor]) -> float:
    """L2 norm of (after - before) across every parameter tensor, treating the whole network as
    one flat vector. A step-size signal, not an overfitting signal by itself: it tracks how far
    Adam moved the weights this epoch, which shrinks as the loss converges to a fixed point
    regardless of whether that fixed point generalizes. It's only suggestive of overfitting
    alongside a widening train/held-out loss gap -- large or non-decaying movement while train
    loss keeps dropping is consistent with the net still chasing (memorizing) individual examples
    rather than settling, but this alone can't distinguish that from a still-useful large update."""
    total_sq = 0.0
    for k, b in before.items():
        a = after[k]
        total_sq += ((a - b) ** 2).sum().item()
    return total_sq ** 0.5


def split_holdout(examples: list[dict], frac: float, seed: int = 0) -> tuple[list[dict], list[dict]]:
    """(train, held-out). The held-out runs must be runs the starting weights have NOT been trained on. materialize marks the current
    round's examples `fresh` (older rounds were part of earlier rounds' training), so when there are fresh runs the held-out set is
    drawn from them only (`frac` of those fresh runs, by run id, so a mainline and its forks never straddle the split). Without that marking
    but with run ids: random runs. Without either (an old dataset): the last `frac` of the list."""
    if frac <= 0 or len(examples) < 50:
        return examples, []
    if all("run" in ex for ex in examples):
        runs = sorted({ex["run"] for ex in examples})
        fresh = sorted({ex["run"] for ex in examples if ex.get("fresh")})
        pool = fresh if len(fresh) >= 2 else runs
        if len(runs) >= 3 and len(pool) >= 2:
            rng = random.Random(seed)
            rng.shuffle(pool)
            k = min(max(1, round(len(pool) * frac)), len(pool) - 1 if pool is fresh else len(pool))  # frac of the POOL it is drawn from
            held = set(pool[:k])
            return [ex for ex in examples if ex["run"] not in held], [ex for ex in examples if ex["run"] in held]
    cut = len(examples) - max(1, int(len(examples) * frac))
    return examples[:cut], examples[cut:]


@torch.no_grad()
def evaluate(examples: list[dict], net: ClawsNet, value_only: bool, batch_size: int, device: torch.device) -> dict[str, float]:
    """Held-out loss with the training objective (advantage-weighted log-likelihood + value MSE in V_SCALE units, per example), and
    its parts, no gradient."""
    net.eval()
    pol = sq = 0.0
    n_scored = 0
    for start in range(0, len(examples), batch_size):
        _loss, p, e, k = _batch_step(examples[start:start + batch_size], net, value_only, device)
        pol, sq, n_scored = pol + p, sq + e, n_scored + k
    net.train()
    n = len(examples)
    return {"loss": (pol + sq / V_SCALE ** 2) / n, "policy": pol / n_scored if n_scored else float("nan"), "rmse": (sq / n) ** 0.5}


def train(
    examples: list[dict], net: ClawsNet, epochs: int, lr: float, seed: int = 0,
    value_only: bool = False, batch_size: int = 64, device: torch.device = torch.device("cpu"),
    holdout: float = 0.1, patience: int = 10, held_examples: list[dict] | None = None,
) -> None:
    """Adam for up to `epochs` epochs. `holdout` of the runs is kept out of training and scored after every epoch; training stops
    once the held-out loss has not improved for `patience` epochs, and the net ends as the best epoch's weights (epoch 0 = the weights
    it started from, so a round that cannot beat them changes nothing). holdout=0: all examples train for all epochs, as before."""
    if held_examples:  # an external held-out set (greedy lines): every example trains, the held-out ones are only scored
        held = held_examples
    else:
        examples, held = split_holdout(examples, holdout, seed)
    _normalize_advantages(examples)
    if held and held_examples:
        print(f"held out {len(held)} external examples (value only: no exploration, no advantages), train on all {len(examples)} "
              f"(early stop: patience {patience})")
    elif held:  # the same scale as the training split, not re-computed on the held-out one
        scored = [ex["advantage"] for ex in examples if ex["action_index"] is not None]
        std = (sum(a * a for a in scored) / len(scored)) ** 0.5 if scored else 0.0
        for ex in held:
            if ex["action_index"] is not None and std > 1e-8:
                ex["advantage"] /= std
        print(f"held out {len(held)} of {len(held) + len(examples)} examples (early stop: patience {patience})")
    target_std = torch.tensor([ex["value"] for ex in examples]).std().item() if len(examples) > 1 else 0.0
    net.to(device)
    opt = torch.optim.Adam(net.parameters(), lr=lr)
    rng = random.Random(seed)
    before = _snapshot(net)
    best_loss, best_epoch, best_state = float("inf"), 0, None
    if held:
        v = evaluate(held, net, value_only, batch_size, device)
        best_loss, best_state = v["loss"], {k: t.detach().cpu().clone() for k, t in net.state_dict().items()}
        print(f"epoch 0/{epochs}: held-out loss={v['loss']:.4f} policy={v['policy']:.4f} value_rmse={v['rmse']:.2f}HP (the weights it started from)")

    for epoch in range(epochs):
        order = list(range(len(examples)))
        rng.shuffle(order)
        total_policy = total_sq_err = 0.0
        n_scored = 0

        for start in range(0, len(order), batch_size):
            batch = [examples[i] for i in order[start:start + batch_size]]
            loss, batch_policy, batch_sq_err, batch_n_scored = _batch_step(
                batch, net, value_only, device
            )

            opt.zero_grad()
            loss.backward()
            opt.step()

            total_policy += batch_policy
            total_sq_err += batch_sq_err
            n_scored += batch_n_scored

        n = len(examples)
        policy_avg = f"{total_policy / n_scored:.4f} (n={n_scored} scored)" if n_scored else "n/a"
        after = _snapshot(net)
        changed, total = _count_changed(before, after)
        l2_delta = _l2_delta(before, after)
        before = after
        line = (f"epoch {epoch + 1}/{epochs}: policy_loss={policy_avg} "
                f"value_rmse={(total_sq_err / n) ** 0.5:.2f}HP (predicting the mean: {target_std:.2f}HP) "
                f"params_changed={changed}/{total} ({changed / total:.1%}) "
                f"param_delta_l2={l2_delta:.4f}")
        if held:
            v = evaluate(held, net, value_only, batch_size, device)
            improved = v["loss"] < best_loss - 1e-6
            if improved:
                best_loss, best_epoch = v["loss"], epoch + 1
                best_state = {k: t.detach().cpu().clone() for k, t in net.state_dict().items()}
            line += (f" | held-out loss={v['loss']:.4f} policy={v['policy']:.4f} value_rmse={v['rmse']:.2f}HP"
                     f"{' *best*' if improved else f' (no gain for {epoch + 1 - best_epoch}/{patience})'}")
        print(line, flush=True)
        if held and epoch + 1 - best_epoch >= patience:
            print(f"early stop: no held-out gain for {patience} epochs")
            break

    if held:
        net.load_state_dict(best_state)
        print(f"kept epoch {best_epoch} (held-out loss {best_loss:.4f})" + (" -- the starting weights: no epoch beat them" if best_epoch == 0 else ""))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("datasets", nargs="*",
                         help="materialize.py output(s), e.g. dataset.pt "
                              "(omit with --epochs 0 to just save an untrained init checkpoint)")
    parser.add_argument("--epochs", type=int, default=5)
    parser.add_argument("--lr", type=float, default=1e-5)
    parser.add_argument("--batch-size", type=int, default=32,
                         help="examples per padded batch (see module docstring). See module "
                              "docstring's CPU/GPU crossover note before raising this -- past "
                              "~256 it's only a win with --device cuda, and the learning rate "
                              "should scale roughly with sqrt(batch_size) for Adam")
    parser.add_argument("--device", default=None, choices=["cpu", "cuda"],
                         help="default: cuda if available, else cpu")
    parser.add_argument("--out", default="claws.pt")
    parser.add_argument("--init", default=None,
                         help="resume from an existing checkpoint, or pass \"\" to train from "
                              "a random init. Required no implicit default. ")
    parser.add_argument("--holdout", type=float, default=0.1,
                         help="share of the runs kept out of training and scored every epoch (default 0.1; 0 = train on everything for "
                              "all --epochs)")
    parser.add_argument("--heldout-file", nargs="*", default=None,
                         help="materialize.py output(s) of greedy lines the net never trained on: used as the held-out set instead of "
                              "--holdout (all examples then train); early stopping follows their value RMSE")
    parser.add_argument("--patience", type=int, default=10,
                         help="stop once the held-out loss has not improved for this many epochs; the best epoch's weights are kept")
    parser.add_argument("--value-only", action="store_true",
                         help="train V only, skipping the policy loss on every example -- for a "
                              "first round, where V is worth fitting before anything uses it")
    args = parser.parse_args()
    device = torch.device(args.device or ("cuda" if torch.cuda.is_available() else "cpu"))
    print(f"training on {device}")
    if args.init is None:
        raise SystemExit("--init is required -- pass a checkpoint path to resume from, or \"\" "
                          "to intentionally train from a random init (e.g. round 1). There is "
                          "no default: a mis-pasted command that drops this flag now fails here "
                          "instead of silently loading whatever \"claws.pt\" happens to resolve "
                          "to in the current directory.")
    if not args.init and os.path.exists(args.out):
        raise SystemExit(f"--init is empty but --out ({args.out}) already exists -- refusing to "
                          f"overwrite a trained checkpoint with a random init. If this really is "
                          f"a fresh start, remove or rename the existing {args.out} first.")

    examples: list[dict] = []
    for path in args.datasets:
        examples.extend(torch.load(path, weights_only=False))
    if examples and any(k not in examples[0] for k in (*PILE_KEYS, "group_ids")):
        raise SystemExit("dataset predates pile tokens (no pile_*/group_ids) -- re-run materialize.py")
    print(f"{len(examples)} training examples from {len(args.datasets)} dataset file(s)")

    net = ClawsNet(GlobalVocab(EntityVocab.load()))
    if args.init:
        net.load_compatible(torch.load(args.init, weights_only=True))
        print(f"resumed from {args.init}")
    else:
        print("--init \"\": training from a random init")

    held_examples = None
    if args.heldout_file:
        held_examples = [ex for path in args.heldout_file for ex in torch.load(path, weights_only=False)]
        print(f"{len(held_examples)} held-out examples from {len(args.heldout_file)} file(s)")
        if not held_examples:  # the greedy lines produced nothing: fall back to splitting the fresh runs
            print(f"no held-out examples: falling back to --holdout {args.holdout or 0.25}")
            args.holdout = args.holdout or 0.25
    if args.epochs > 0:
        if not examples:
            raise SystemExit("no examples loaded -- pass a dataset, or --epochs 0 to just save "
                              "an untrained init checkpoint")
        train(examples, net, epochs=args.epochs, lr=args.lr, value_only=args.value_only,
              batch_size=args.batch_size, device=device, holdout=args.holdout, patience=args.patience, held_examples=held_examples or None)
    else:
        print("--epochs 0: skipping training, saving weights as-is")

    net.to("cpu")  # checkpoints stay device-agnostic regardless of what trained them
    torch.save(net.state_dict(), args.out)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
